import assert from 'node:assert/strict';
import fs from 'node:fs';
import {launch} from '../skills/awwwards/scripts/browser.mjs';
const browser=await launch();
const out='.shots/motion';fs.mkdirSync(out,{recursive:true});
try {
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:4400/',{waitUntil:'networkidle'});
  await page.waitForTimeout(1500);
  const before=await page.locator('.hero-cat-left .cat-tail').getAttribute('transform');
  await page.screenshot({path:`${out}/hero-a.png`});
  await page.waitForTimeout(650);
  const after=await page.locator('.hero-cat-left .cat-tail').getAttribute('transform');
  assert.notEqual(before,after,'The tail must animate independently, rather than moving the whole cat only.');
  await page.screenshot({path:`${out}/hero-b.png`});
  assert.equal(await page.locator('.hero-cat-right .cat image').count(),0,'Orange mascot matches the native flat SVG illustration family.');
  assert.equal(await page.locator('.hero-cat-right .cat-head,.hero-cat-right .cat-tail,.hero-cat-right .cat-eyes').count(),3);
  const newCat=page.locator('.hero-cat-right .cat-body');
  const newCatPose=await newCat.getAttribute('transform');
  await page.waitForTimeout(400);
  assert.notEqual(await newCat.getAttribute('transform'),newCatPose,'The flat orange mascot keeps its articulated animation.');
  await page.locator('#services').scrollIntoViewIfNeeded();
  await page.locator('[data-pick-service="food"]').click();
  assert.equal(await page.locator('[data-pick-service="food"]').getAttribute('aria-pressed'),'true');
  assert.equal(await page.locator('[data-playground-character="food"]').isVisible(),true);
  await page.locator('#playground').scrollIntoViewIfNeeded();
  await page.locator('#creative-energy').focus();
  await page.keyboard.press('End');
  for(let i=0;i<5;i++)await page.keyboard.press('ArrowLeft');
  assert.equal(await page.locator('#energy-state').textContent(),'Full purr-sonality');
  const cat=page.locator('[data-playground-character="food"] .cat-body');
  const energetic=await cat.getAttribute('transform');
  await page.waitForTimeout(450);
  assert.notEqual(await cat.getAttribute('transform'),energetic,'The selected playground character must keep moving.');
  await page.screenshot({path:`${out}/playground.png`});
  await page.locator('[data-pet-cat]').first().click();
  assert.match(await page.locator('#playground-status').textContent(),/prrrr/i);
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('http://127.0.0.1:4400/',{waitUntil:'networkidle'});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.waitForTimeout(250);
  const still=await page.locator('.hero-cat-left .cat-tail').getAttribute('transform');
  await page.waitForTimeout(400);
  assert.notEqual(await page.locator('.hero-cat-left .cat-tail').getAttribute('transform'),still);
  await page.locator('[data-pick-service="resumes"]').click();
  assert.equal(await page.locator('[data-playground-character="resumes"]').isVisible(),true);
  assert.deepEqual(errors,[]);
  fs.writeFileSync(`${out}/results.json`,JSON.stringify({passed:true,tailTransforms:{before,after},checks:['independent articulated tail animation','character selection updates playground and package category','keyboard-accessible energy control reaches 95 and changes state','selected character continues moving','petting produces live feedback','reduced motion stops character movement while selection works','zero browser JavaScript errors']},null,2));
  console.log('PASS matching flat SVG mascot motion, service selection, energy slider, petting and owner-requested always-on animation.');
}finally{await browser.close();}
